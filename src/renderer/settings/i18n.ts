export const STRINGS: Record<Language, Record<StringKey, string>> = { de, en }

let current: Language = 'de'

export function setLanguage(lang: Language): void {
  current = lang in STRINGS ? lang : 'de'
}

export function getLanguage(): Language {
  return current
}

export type Vars = Record<string, string | number>

function substitute(text: string, vars?: Vars): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

/** Translate in an explicit language. */
export function tl(key: StringKey, lang: Language, vars?: Vars): string {
  const table = STRINGS[lang] ?? STRINGS.de
  return substitute(table[key] ?? STRINGS.de[key] ?? key, vars)
}

/** Translate in the current language. */
export function t(key: StringKey, vars?: Vars): string {
  return tl(key, current, vars)
}
